// Regenerates the bundled models.dev price snapshot. Run after `npm run build:typescript`:
//   node packages/host-runtime/scripts/update-model-prices.mjs
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { MODELS_DEV_URL, compactModelsDev } from "../dist/model-prices.js";

const target = fileURLToPath(new URL("../src/model-prices.generated.ts", import.meta.url));
const response = await fetch(MODELS_DEV_URL, { signal: AbortSignal.timeout(60_000) });
if (!response.ok) throw new Error(`models.dev responded ${response.status}`);
const table = { fetchedAtMs: Date.now(), providers: compactModelsDev(await response.json()) };
await writeFile(
  target,
  [
    "// Generated by packages/host-runtime/scripts/update-model-prices.mjs from https://models.dev (MIT).",
    "// Do not edit by hand.",
    'import type { ModelPriceTableData } from "./model-prices.js";',
    "",
    `export const bundledModelPrices: ModelPriceTableData = ${JSON.stringify(table)};`,
    "",
  ].join("\n"),
);
console.log(`Wrote ${target}`);
