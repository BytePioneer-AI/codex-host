import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { build } from "esbuild";
import { format, resolveConfig } from "prettier";

const root = path.resolve(import.meta.dirname, "..");
const outfile = path.join(root, "registry/desktop-extensions/runtime.mjs");
const { outputFiles } = await build({
  stdin: {
    contents: `
      export {
        DESKTOP_EXTENSION_ICON_MAX_BYTES, DESKTOP_EXTENSION_MANIFEST_MAX_BYTES,
        DESKTOP_EXTENSION_SCRIPT_MAX_BYTES,
        DESKTOP_EXTENSION_STYLE_MAX_BYTES, DESKTOP_EXTENSION_SCREENSHOT_MAX_BYTES,
        DESKTOP_EXTENSION_ZIP_MAX_BYTES, compareExtensionVersions, desktopExtensionCatalogSchema,
        desktopExtensionCatalogEntrySchema, desktopExtensionHttpUrlSchema,
        desktopExtensionIdSchema, desktopExtensionManifestSchema,
        desktopExtensionScreenshotMimeType, desktopExtensionZipUrlSchema,
        isGitHubDesktopExtensionZipballUrl
      } from './packages/shared-contracts/src/desktop-extensions.ts';
      export { readDesktopExtensionZip } from './packages/harness-plugin-files/src/extension-zip.ts';
    `,
    resolveDir: root,
  },
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node24",
  external: ["zod"],
  alias: {
    "@codexhost/shared-contracts": path.join(
      root,
      "packages/shared-contracts/src/desktop-extensions.ts",
    ),
  },
  write: false,
});
const source = await format(
  `// Generated by tools/export-desktop-extension-registry.mjs. Do not edit.\n${outputFiles[0].text}`,
  { ...(await resolveConfig(outfile)), filepath: outfile },
);
if (process.argv.includes("--check")) {
  if ((await readFile(outfile, "utf8")) !== source)
    throw new Error("Registry runtime is out of date");
} else {
  await writeFile(outfile, source);
}
